#!/usr/bin/env python3
"""
Minimal kconfig.py — 替代 Zephyr 的 scripts/kconfig.py
兼容旧版 kconfiglib (< 14.1.0)
同时生成 C 头文件 (.h) 和 Verilog 头文件 (.svh)

用法:
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --kconfig-list-out log.txt \
        --configs-in .config

    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --header-out csrc/include/autoconfig.h \
        --kconfig-list-out log.txt \
        --configs-in .config

    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --header-out csrc/include/autoconfig.h \
        --verilog-header build/config.svh \
        --kconfig-list-out log.txt \
        --configs-in .config

示例:
    # 只生成 .config 和文件列表（不生成任何头文件）
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --kconfig-list-out log.txt \
        --configs-in .config

    # 只生成 C 头文件
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --header-out csrc/include/autoconfig.h \
        --kconfig-list-out log.txt \
        --configs-in .config

    # 只生成 Verilog 头文件
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --verilog-header build/config.svh \
        --kconfig-list-out log.txt \
        --configs-in .config

    # 同时生成 C + Verilog 头文件
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --header-out csrc/include/autoconfig.h \
        --verilog-header build/config.svh \
        --kconfig-list-out log.txt \
        --configs-in .config

    # 合并多个配置文件
    python scripts/kconfig.py \
        --kconfig-file Kconfig \
        --config-out .config \
        --header-out csrc/include/autoconfig.h \
        --verilog-header build/config.svh \
        --kconfig-list-out log.txt \
        --configs-in board_defconfig prj.conf .config
"""

import argparse
import os
import sys
from kconfiglib import Kconfig, BOOL, TRISTATE, INT, HEX, STRING


def _verilog_used(kconf, sym):
    """判断 sym 是否应该导出到 Verilog 头文件（通过是否 select 过 _ENABLE_VERILOG）"""
    try:
        selects = sym.selects or []
    except Exception:
        return False
    marker_name = "_ENABLE_VERILOG"
    for sel in selects:
        # sel 的结构可能是 (expr, cond) 或类似；安全地取第一个元素的 name
        try:
            item = sel[0] if isinstance(sel, (list, tuple)) else sel
            if hasattr(item, 'name') and item.name == marker_name:
                return True
            if hasattr(item, 'orig_name') and item.orig_name == marker_name:
                return True
        except Exception:
            continue
    return False


def write_verilog_header(kconf, filename):
    """把 kconfig 配置转成 Verilog localparam"""
    os.makedirs(os.path.dirname(filename) or '.', exist_ok=True)
    with open(filename, 'w') as f:
        f.write("// Auto-generated by kconfig.py — DO NOT EDIT\n")
        f.write("//\n")
        f.write("// Usage: `include \"%s\"\n\n" % filename)

        for name, sym in sorted(kconf.syms.items()):
            if name.startswith('_') or name in ('MODULES', 'UNAME_RELEASE'):
                continue
            if not sym.str_value:
                continue
            if sym.type in (BOOL, TRISTATE) and sym.str_value == 'n':
                continue

            # 【过滤】只输出 Kconfig 里标记了 select _ENABLE_VERILOG 的符号
            if not _verilog_used(kconf, sym):
                continue

            vname = "CONFIG_" + name

            if sym.type in (BOOL, TRISTATE):
                f.write(f"localparam {vname} = 1;\n")
            elif sym.type == STRING:
                f.write(f'localparam string {vname} = "{sym.str_value}";\n')
            elif sym.type == INT:
                # 十进制整数直接输出
                f.write(f"localparam {vname} = {sym.str_value};\n")
            elif sym.type == HEX:
                # 【关键修复】十六进制必须加 32'h 前缀，否则 Verilator 会把 0x 当成标识符报错
                hex_val = sym.str_value.lower().removeprefix('0x').removeprefix('0X')
                f.write(f"localparam {vname} = 32'h{hex_val};\n")

def parse_args():
    parser = argparse.ArgumentParser(
        allow_abbrev=False,
        description="Merge Kconfig fragments, output .config, C header and optionally Verilog header.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--kconfig-file",
        required=True,
        help="Top-level Kconfig file",
    )
    parser.add_argument(
        "--config-out",
        required=True,
        help="Output .config file",
    )
    parser.add_argument(
        "--header-out",
        default=None,
        help="Output C header file (autoconfig.h). If omitted, skip.",
    )
    parser.add_argument(
        "--verilog-header",
        default=None,
        help="Output Verilog header file (.svh). If omitted, skip.",
    )
    parser.add_argument(
        "--kconfig-list-out",
        required=True,
        help="Output list of parsed Kconfig filenames",
    )
    parser.add_argument(
        "--configs-in",
        nargs="+",
        required=True,
        help="Input configuration fragments (merged in order)",
    )
    return parser.parse_args()


def main():
    args = parse_args()

    # 1. 解析 Kconfig
    print("Parsing " + args.kconfig_file)
    kconf = Kconfig(args.kconfig_file)

    # 2. 依次加载配置文件（合并）
    for conf in args.configs_in:
        replace = (conf == args.configs_in[0])
        print(kconf.load_config(conf, replace=replace))

    # 3. 写出合并后的 .config
    print(kconf.write_config(args.config_out))

    # 4. 写出 C 头文件（可选）
    if args.header_out:
        print(kconf.write_autoconf(args.header_out))
    else:
        print("Skipped C header (--header-out not specified)")

    # 5. 写出 Verilog 头文件（可选）
    if args.verilog_header:
        write_verilog_header(kconf, args.verilog_header)
        print("Verilog header saved to '" + args.verilog_header + "'")
    else:
        print("Skipped Verilog header (--verilog-header not specified)")

    # 6. 写出解析过的 Kconfig 文件列表
    os.makedirs(os.path.dirname(args.kconfig_list_out) or '.', exist_ok=True)
    with open(args.kconfig_list_out, 'w') as f:
        for path in sorted(set(kconf.kconfig_filenames)):
            f.write(os.path.realpath(os.path.join(kconf.srctree, path)) + '\n')


if __name__ == "__main__":
    main()
